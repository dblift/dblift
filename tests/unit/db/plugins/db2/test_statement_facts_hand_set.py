@pytest.mark.parametrize(("family", "sql", "operation", "schema", "name"), HAND_SET)
def test_hand_set_statement(family, sql, operation, schema, name):
    facts = READ(sql)
    if operation is None:
        assert facts.objects == ()
        assert facts.opaque
        return
    assert facts.operation == operation
    if operation in KINDS:
        assert facts.kind == KINDS[operation]
    if name is None:
        assert facts.objects == ()
        return
    assert (facts.objects[0].schema, facts.objects[0].name) == (schema, name)
