"""Only source-proven column clauses can complete a mixed ALTER key declaration."""

import pytest

from dblift.core.sql_parser.statement_facts import DeclaredConstraint
from dblift.db.provider_registry import ProviderRegistry


def _read(dialect, detail, companion="a"):
    sql = f"ALTER TABLE t ADD UNIQUE({companion}), ADD COLUMN b INT {detail}"
    return ProviderRegistry.get_quirks(dialect).statement_facts_reader().read(sql)


@pytest.mark.parametrize("inline", ["", "UNIQUE "])
@pytest.mark.parametrize(
    "dialect,clause",
    [
        ("postgresql", "NOT FOR REPLICATION"),
        ("postgresql", "AFTER a"),
        ("postgresql", "FIRST"),
        ("postgresql", "AUTO_INCREMENT"),
        ("postgresql", "COMMENT 'x'"),
        ("mysql", "NOT FOR REPLICATION"),
        ("mariadb", "NOT FOR REPLICATION"),
        ("mysql", "GENERATED ALWAYS AS IDENTITY"),
    ],
)
def test_foreign_column_clause_cannot_certify_mixed_keys(dialect, clause, inline):
    facts = _read(dialect, inline + clause)
    assert facts.opaque
    assert facts.declared_columns == ()
    assert facts.declared_constraints == ()


@pytest.mark.parametrize("dialect", ["mysql", "mariadb"])
@pytest.mark.parametrize("inline", ["", "PRIMARY KEY "])
@pytest.mark.parametrize(
    "clause",
    ["AUTO_INCREMENT", "COMMENT 'x'", "FIRST", "AFTER a", "AFTER `123`", "AFTER `signal`"],
)
def test_mysql_family_column_grammar_preserves_keys(dialect, inline, clause):
    companion = "a" if inline else "b"
    facts = _read(dialect, inline + clause, companion)
    expected = (DeclaredConstraint("UNIQUE", (companion,)),)
    if inline:
        expected += (DeclaredConstraint("PRIMARY_KEY", ("b",)),)
    assert facts.declared_constraints == expected
    assert facts.declared_columns == ("b",)
    assert not facts.opaque


@pytest.mark.parametrize("dialect", ["mysql", "mariadb"])
@pytest.mark.parametrize("inline", ["", "PRIMARY KEY "])
@pytest.mark.parametrize(
    "position",
    [
        "AFTER",
        "AFTER 123",
        "AFTER ``",
        "AFTER 'a'",
        "AFTER a.b",
        "AFTER SIGNAL",
        "BEFORE a",
        "FIRST a",
    ],
)
def test_mysql_family_position_requires_a_plain_column_role(dialect, position, inline):
    facts = _read(dialect, inline + position)
    assert facts.opaque
    assert facts.declared_columns == ()
    assert facts.declared_constraints == ()


def test_pg_plain_identity_clause_with_mixed_keys():
    facts = _read("postgresql", "GENERATED BY DEFAULT AS IDENTITY")
    assert not facts.opaque
    assert facts.declared_columns == ("b",)
    assert facts.declared_constraints == (DeclaredConstraint("UNIQUE", ("a",)),)
